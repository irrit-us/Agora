def get_language_template(language: str) -> str:
    """
    Get the language-specific test template.
    """
    language = language.lower()

    templates = {
        "go": GO_TEST_TEMPLATE,
        "rust": RUST_TEST_TEMPLATE,
        "java": JAVA_TEST_TEMPLATE + "\n" + JAVA_JUNIT4_TEST_TEMPLATE,
        "cpp": CPP_TEST_TEMPLATE,
    }

    if language in templates:
        return templates[language]
    else:
        # Unknown language - return a generic message instead of defaulting to Go
        return f"""
## Unknown Language: {language}

Please check the repository to understand its test structure and conventions.
Use `repo_knowledge()` to get test patterns and helper functions.

Common test patterns:
- Look for existing test files in the repository
- Follow the naming conventions used by other tests
- Use the same assertion style as existing tests
"""



def get_testgen_prompt(
    attack_scenario: str, protocol_name: str, language: str, repo_knowledge: str = ""
) -> str:
    """
    Build the complete testgen prompt with context.

    Args:
        attack_scenario: The attack scenario to transform into test code
        protocol_name: Name of the protocol being tested
        language: Programming language (go, rust, java, cpp)
        repo_knowledge: Pre-loaded repository knowledge

    Returns:
        Complete prompt string for test generation
    """
    prompt_parts = [TESTGEN_SYSTEM_PROMPT]

    # Add language-specific template
    language_template = get_language_template(language)
    prompt_parts.append(
        f"""
## Language-Specific Template

{language_template}
"""
    )

    prompt_parts.append(
        f"""
## Target Protocol

- **Name**: {protocol_name}
- **Language**: {language}

## Attack Scenario

{attack_scenario}
"""
    )

    if repo_knowledge:
        prompt_parts.append(
            f"""
## Repository Knowledge (Pre-loaded)

{repo_knowledge}
"""
        )

    # Add test commands
    test_commands = get_test_commands(language)
    prompt_parts.append(test_commands)

    prompt_parts.append(
        """
## Task

1. Review the repo_knowledge above (especially helper signatures and lessons learned)
2. Use the language-specific template as a guide for code structure
3. Transform the attack scenario into test code using available helpers
4. Ensure code can compile and run
5. Execute test and report results
6. If errors occur: search lessons -> fix -> record lesson

Now begin...
"""
    )

    return "\n".join(prompt_parts)
